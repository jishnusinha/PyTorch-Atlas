import fs from "node:fs";

const scripts = {
  "bs01-house-price": "python_projects/bs01_house_price/train.py",
  "bs02-wisconsin-cancer": "python_projects/bs02_wisconsin_cancer/train.py",
  "bs03-synthetic-churn": "python_projects/bs03_synthetic_churn/train.py",
  "bs04-fashion-ann": "python_projects/bs04_fashion_ann/train.py",
  "bs05-fashion-cnn": "python_projects/bs05_fashion_cnn/train.py",
};
const entries = Object.entries(scripts).map(([id, path]) => `  ${JSON.stringify(id)}: ${JSON.stringify(fs.readFileSync(path, "utf8"))},`);
fs.writeFileSync("src/content/projectScripts.ts", `// Generated by scripts/generate-project-scripts.mjs. Keep Python projects as the editable source.\nexport const projectScripts: Record<string, string> = {\n${entries.join("\n")}\n};\n`);
console.log(`Bundled ${Object.keys(scripts).length} standalone project scripts.`);
